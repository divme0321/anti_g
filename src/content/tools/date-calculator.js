<h2>うるう年と月末日の扱い — 「1月31日の1ヶ月後」問題</h2>
<p>日単位・週単位の計算は機械的に足し引きするだけですが、<strong>月単位・年単位の加減算には「存在しない日付」の問題</strong>がつきまといます。たとえば1月31日の1ヶ月後は、カレンダー上「2月31日」が存在しないため、一般的には2月末日（平年なら2月28日、うるう年なら2月29日）とみなします。同様に、うるう年の2月29日の1年後も、翌年に2月29日がないため2月28日として扱うのが自然です。</p>
<p>JavaScriptで日付計算を自前で実装する場合、この点が落とし穴になります。<code>Date</code> の <code>setMonth()</code> は存在しない日付を自動的に繰り上げるため、<code>new Date(2026, 0, 31)</code>（1月31日）に <code>setMonth(1)</code> を適用すると、2月31日→<strong>3月3日</strong>に化けてしまいます。期待する「2月28日」とは大きくずれるため、月の加減算では「移動先の月の末日を調べ、元の日がそれを超える場合は末日に丸める」という補正が必要です。本ツールはこの補正を実装済みで、1月31日の1ヶ月後は正しく2月末日になります。</p>
